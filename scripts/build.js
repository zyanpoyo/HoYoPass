import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FLAVORS } from '../src/config/flavors.js';

// コマンドライン引数の解析
const args = process.argv.slice(2);
const flavorArg = args.find(a => !a.startsWith('--')) || 'dev';
const isWatch = args.includes('--watch');

if (!FLAVORS[flavorArg]) {
  console.error(`❌ 不正なフレーバー指定: "${flavorArg}". 有効なフレーバー: ${Object.keys(FLAVORS).join(', ')}`);
  process.exit(1);
}

const targetFlavor = FLAVORS[flavorArg];
const rootDir = path.resolve('.');
const outDir = path.resolve(rootDir, 'dist', targetFlavor.flavor);

// ディレクトリ再帰コピーヘルパー
function copyDirRecursive(src, dest) {
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(dest, { recursive: true });
  }
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

// ビルド処理の本体
export function buildFlavor(flavorName = flavorArg) {
  const flavor = FLAVORS[flavorName];
  const targetOutDir = path.resolve(rootDir, 'dist', flavor.flavor);

  console.log(`🔨 [Build] フレーバー "${flavor.flavor}" のビルドを開始します...`);

  // 1. 出力ディレクトリの準備
  if (fs.existsSync(targetOutDir)) {
    fs.rmSync(targetOutDir, { recursive: true, force: true });
  }
  fs.mkdirSync(targetOutDir, { recursive: true });

  // 2. manifest.json の生成（フレーバー用カスタマイズを注入）
  const baseManifestPath = path.resolve(rootDir, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(baseManifestPath, 'utf8'));

  manifest.name = `${manifest.name}${flavor.manifest.nameSuffix}`;
  manifest.short_name = `${manifest.short_name}${flavor.manifest.shortNameSuffix}`;
  if (flavor.manifest.versionNameSuffix) {
    manifest.version_name = `${manifest.version}${flavor.manifest.versionNameSuffix}`;
  }

  fs.writeFileSync(
    path.join(targetOutDir, 'manifest.json'),
    JSON.stringify(manifest, null, 2),
    'utf8'
  );

  // 3. src/ ディレクトリのコピー
  const srcDest = path.join(targetOutDir, 'src');
  copyDirRecursive(path.resolve(rootDir, 'src'), srcDest);

  // 4. src/config/env.js の自動生成（ビルド対象フレーバーの設定を書き込み）
  const envContent = `// [Auto-Generated by scripts/build.js for flavor: ${flavor.flavor}]
export const CURRENT_FLAVOR = ${JSON.stringify(flavor.flavor)};
export const FLAVOR_CONFIG = ${JSON.stringify(flavor, null, 2)};
`;
  fs.writeFileSync(path.join(srcDest, 'config', 'env.js'), envContent, 'utf8');

  // 5. アセットおよび共通ファイルのコピー
  const staticDirs = ['icons', 'assets'];
  for (const dir of staticDirs) {
    const srcDir = path.resolve(rootDir, dir);
    if (fs.existsSync(srcDir)) {
      copyDirRecursive(srcDir, path.join(targetOutDir, dir));
    }
  }

  const staticFiles = ['LICENSE', 'NOTICE'];
  for (const file of staticFiles) {
    const srcFile = path.resolve(rootDir, file);
    if (fs.existsSync(srcFile)) {
      fs.copyFileSync(srcFile, path.join(targetOutDir, file));
    }
  }

  console.log(`✅ [Build] 出力完了: ${targetOutDir}`);
  console.log(`   ・名称: ${manifest.name}`);
  console.log(`   ・定期実行間隔: ${flavor.config.REDEEM_INTERVAL_MINUTES}分`);
  console.log(`   ・起動ディレイ: ${flavor.config.CATCH_UP_DELAY_MS}ms`);
}

// 単体実行時のエントリポイント
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  buildFlavor(flavorArg);

  if (isWatch) {
    console.log(`👀 [Watch] ソースファイルの変更を監視しています... (Ctrl+C で終了)`);
    const watchDirs = ['src', 'icons', 'assets', 'manifest.json'];
    let debounceTimer = null;

    for (const item of watchDirs) {
      const fullPath = path.resolve(rootDir, item);
      if (fs.existsSync(fullPath)) {
        fs.watch(fullPath, { recursive: true }, (eventType, filename) => {
          if (!filename || filename.includes('env.js')) return;
          if (debounceTimer) clearTimeout(debounceTimer);
          debounceTimer = setTimeout(() => {
            console.log(`🔄 変更を検知しました (${filename}): 再ビルド中...`);
            buildFlavor(flavorArg);
          }, 300);
        });
      }
    }
  }
}
